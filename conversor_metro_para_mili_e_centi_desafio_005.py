distancia = float(input('Digite o valor da distancia em metros: '))

#Formula de conversao de metros para Quilometros
print('A distancia em Quilometros, e de: {:.0f} km'. format(distancia/1000))

#Formula de conversao de metros para hectometros
print('A distancia em hectometro, e de: {:.0f} hm'. format(distancia/100))

#Formula de conversao de metros para decametros
print('A distancia em decametros, e de: {:.0f} dam'. format(distancia/10))

#Formula de conversao de metros para decimetros
print('A distancia em decimetros, e de: {:.0f} dm'. format(distancia*10))

#Formula de conversao de metros para centimetros
print('A distancia em centimetros e de: {:.0f} cm'. format(distancia*100))

#Formula de conversao de metros para milimetros
print('A distancia em milimetros e de: {:.0f} mm'. format(distancia*1000))